"""
Evaluation pipeline using Pydantic AI for assessing answer quality.

This module uses Pydantic AI's evaluation framework to measure
accuracy, confidence calibration, and reasoning quality.

Uses OpenRouter for both the main API and the Pydantic AI evaluator.
Only requires OPENROUTER_API_KEY in your .env file.
"""

import asyncio
import json
import os
from pathlib import Path
from typing import Any

from fastapi.testclient import TestClient
from pydantic import BaseModel, Field
from pydantic_ai import Agent
from pydantic_ai.models.openai import OpenAIModel

from app.env import get_openrouter_api_key, get_openrouter_model
from app.main import app
from app.models import AnswerInput, Patient, Question, QuestionSet


class AnswerEvaluation(BaseModel):
    """Evaluation result for a single answer."""

    accuracy_score: float = Field(
        ge=0.0, le=1.0, description="How accurate is the answer? 1.0 = perfect"
    )
    confidence_appropriate: float = Field(
        ge=0.0,
        le=1.0,
        description="Is confidence level appropriate? 1.0 = perfectly calibrated",
    )
    reasoning_quality: float = Field(
        ge=0.0, le=1.0, description="Quality of reasoning explanation"
    )
    explanation: str = Field(description="Brief explanation of the evaluation")


class EvaluationMetrics:
    """Container for aggregated evaluation metrics."""

    def __init__(self):
        self.results = []
        self.passed = 0
        self.failed = 0

    def add_result(self, case_name: str, evaluation: AnswerEvaluation, passed: bool):
        """Add an evaluation result."""
        self.results.append(
            {
                "case": case_name,
                "accuracy": evaluation.accuracy_score,
                "confidence": evaluation.confidence_appropriate,
                "reasoning": evaluation.reasoning_quality,
                "passed": passed,
                "explanation": evaluation.explanation,
            }
        )
        if passed:
            self.passed += 1
        else:
            self.failed += 1

    def get_summary(self) -> dict[str, Any]:
        """Get summary statistics."""
        if not self.results:
            return {}

        total = len(self.results)
        return {
            "total_cases": total,
            "passed": self.passed,
            "failed": self.failed,
            "pass_rate": self.passed / total if total > 0 else 0,
            "avg_accuracy": sum(r["accuracy"] for r in self.results) / total,
            "avg_confidence_score": sum(r["confidence"] for r in self.results) / total,
            "avg_reasoning_quality": sum(r["reasoning"] for r in self.results) / total,
            "overall_score": sum(
                r["accuracy"] + r["confidence"] + r["reasoning"] for r in self.results
            )
            / (total * 3),  # Average of all three metrics
        }


def load_test_cases() -> list[dict]:
    """Load evaluation test cases from JSON file."""
    # Load from sample_data directory instead of fixtures
    sample_data_path = (
        Path(__file__).parent.parent / "sample_data" / "eval_test_cases.json"
    )
    with open(sample_data_path) as f:
        return json.load(f)


async def create_evaluator_agent():
    """Create a Pydantic AI agent for evaluating answers."""
    # Configure Pydantic AI to use OpenRouter by setting environment variables
    # This way we don't need a separate OpenAI key
    os.environ["OPENAI_API_KEY"] = get_openrouter_api_key()
    os.environ["OPENAI_BASE_URL"] = "https://openrouter.ai/api/v1"

    # Use the same model as the main API
    model = OpenAIModel(get_openrouter_model())

    system_prompt = """You are an expert evaluator for medical AI systems.

Your job is to evaluate answers generated by an AI assistant for prior authorization forms.

Evaluate based on:
1. Accuracy: Is the answer correct given the patient information?
2. Confidence Appropriateness: Is the confidence score appropriate?
   - 1.0 = Explicit information stated clearly
   - 0.7-0.9 = Strong inference from available data
   - 0.4-0.6 = Weak evidence or ambiguous
   - 0.0-0.2 = Information not available
3. Reasoning Quality: Does the reasoning cite specific evidence?

Be strict but fair. Medical AI systems need high standards."""

    agent = Agent(model, result_type=AnswerEvaluation, system_prompt=system_prompt)

    return agent


async def evaluate_answer(
    agent: Agent, answer: dict, expected: dict, case_name: str
) -> AnswerEvaluation:
    """
    Use Pydantic AI agent to evaluate an answer.

    Args:
        agent: Pydantic AI evaluation agent
        answer: The actual answer from the API
        expected: Expected answer criteria
        case_name: Name of test case

    Returns:
        AnswerEvaluation with scores and explanation
    """
    evaluation_prompt = f"""Evaluate this answer from a prior authorization AI system:

Test Case: {case_name}

Question: {answer["question"]["content"]}
Question Type: {answer["question"]["type"]}

Generated Answer:
- Value: {answer["value"]}
- Confidence: {answer["confidence"]:.2f}
- Reasoning: {answer["reasoning"]}

Expected Criteria:
{json.dumps(expected, indent=2)}

Evaluate the answer on accuracy, confidence appropriateness, and reasoning quality.
Consider:
- Does the answer match what's expected?
- Is the confidence level appropriate for the strength of evidence?
- Does the reasoning cite specific information?"""

    result = await agent.run(evaluation_prompt)
    return result.output


async def run_evaluation() -> EvaluationMetrics:
    """
    Run the full evaluation pipeline using Pydantic AI.

    Returns:
        EvaluationMetrics with results
    """
    print("=" * 80)
    print("Pydantic AI Evaluation Pipeline")
    print("=" * 80)
    print()

    # Create evaluator agent
    print("Initializing Pydantic AI evaluator agent...")
    agent = await create_evaluator_agent()
    print("✓ Evaluator ready\n")

    # Create TestClient to call the actual HTTP endpoint
    client = TestClient(app)

    test_cases = load_test_cases()
    metrics = EvaluationMetrics()

    for i, test_case in enumerate(test_cases, 1):
        case_name = test_case["name"]
        print(f"[{i}/{len(test_cases)}] Evaluating: {case_name}")
        print()

        try:
            # Prepare request
            patient = Patient(**test_case["patient"])
            question = Question(**test_case["question"])
            question_set = QuestionSet(name="Evaluation", questions=[question])
            request_data = AnswerInput(patient=patient, question_set=question_set)

            # Call the actual /answers HTTP endpoint
            response = client.post("/answers", json=request_data.model_dump())

            # Check for errors
            if response.status_code != 200:
                raise Exception(
                    f"API returned {response.status_code}: {response.json()}"
                )

            # Parse response
            result = response.json()
            answer = result["answers"][0]

            # Print question and answer
            print(f"  📋 Question: {question.content}")
            print(f"  💬 Answer: {answer['value']}")
            print(f"  🎯 Confidence: {answer['confidence']:.2f}")
            print(f"  🧠 Reasoning: {answer['reasoning']}")
            print()

            # Evaluate using Pydantic AI agent
            evaluation = await evaluate_answer(
                agent, answer, test_case["expected"], case_name
            )

            # Determine pass/fail based on overall quality
            overall_score = (
                evaluation.accuracy_score
                + evaluation.confidence_appropriate
                + evaluation.reasoning_quality
            ) / 3
            passed = overall_score >= 0.7  # 70% threshold

            # Record result
            metrics.add_result(case_name, evaluation, passed)

            # Print evaluation result
            status = "✅ PASS" if passed else "❌ FAIL"
            print(f"  {status} (Overall Score: {overall_score:.2f})")
            print(f"    • Accuracy: {evaluation.accuracy_score:.2f}")
            print(
                f"    • Confidence Calibration: {evaluation.confidence_appropriate:.2f}"
            )
            print(f"    • Reasoning Quality: {evaluation.reasoning_quality:.2f}")
            print(f"  📝 Evaluation: {evaluation.explanation}")
            print()
            print("-" * 80)
            print()

        except Exception as e:
            print(f"  ❌ ERROR: {str(e)}")
            # Create a failed evaluation
            failed_eval = AnswerEvaluation(
                accuracy_score=0.0,
                confidence_appropriate=0.0,
                reasoning_quality=0.0,
                explanation=f"Test execution failed: {str(e)}",
            )
            metrics.add_result(case_name, failed_eval, False)
            print()
            print("-" * 80)
            print()

    return metrics


def print_summary(metrics: EvaluationMetrics):
    """Print evaluation summary."""
    summary = metrics.get_summary()

    if not summary:
        print("No evaluation results to display.")
        return

    print("=" * 80)
    print("Evaluation Summary (Powered by Pydantic AI)")
    print("=" * 80)
    print()
    print(f"Total Test Cases:     {summary['total_cases']}")
    print(f"Passed:               {summary['passed']} ({summary['pass_rate']:.1%})")
    print(f"Failed:               {summary['failed']}")
    print()
    print("Quality Metrics:")
    print(f"  Accuracy:           {summary['avg_accuracy']:.2f}")
    print(f"  Confidence Score:   {summary['avg_confidence_score']:.2f}")
    print(f"  Reasoning Quality:  {summary['avg_reasoning_quality']:.2f}")
    print(f"  Overall Score:      {summary['overall_score']:.2f}")
    print()

    # Show failed cases with details
    failed_cases = [r for r in metrics.results if not r["passed"]]
    if failed_cases:
        print("Failed Cases:")
        for failure in failed_cases:
            print(f"  • {failure['case']}")
            print(
                f"    Scores: A={failure['accuracy']:.2f}, "
                f"C={failure['confidence']:.2f}, R={failure['reasoning']:.2f}"
            )
            print(f"    {failure['explanation']}")
        print()

    # Overall grade
    if summary["overall_score"] >= 0.9:
        grade = "🎉 EXCELLENT"
    elif summary["overall_score"] >= 0.75:
        grade = "✅ GOOD"
    elif summary["overall_score"] >= 0.6:
        grade = "⚠️  NEEDS IMPROVEMENT"
    else:
        grade = "❌ POOR"

    print(f"Overall Grade: {grade}")
    print("=" * 80)


async def main():
    """Run the evaluation pipeline."""
    metrics = await run_evaluation()
    print_summary(metrics)


if __name__ == "__main__":
    asyncio.run(main())
